def study_3():
  class Calc:
      def __init__(self, nums):
          self.nums = nums

      def even_info(self):
          count = 0
          r = []

          for n in self.nums:
              if n % 2 == 0:
                  count += 1
                  r.append(n)

          return r, count


  nums = [1, 2, 3, 4]
  obj = Calc(nums)

  result, count = obj.even_info()

  print(result)
  print(count)
study_3()