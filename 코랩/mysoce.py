def study_1():
  nums = [1,2,3,4,5,6]
  r = []
  count = 0
  add = 0

  for n in nums:
    if n % 2 ==0:
      count +=1
      add += n
      r.append(n)
  average = add /count

  print(r)
  print(count)
  print(add)
  print(average)
study_1()

