def study_2():
  nums = list(map(int, input().split()))
  r = []
  count = 0
  add = 0

  for n in nums:
      if n % 3 ==0:
        count +=1
        add += n
        r.append(n)

  if count > 0:
      average = add /count
  else:
      average = 0

  print(r)
  print(count)
  print(add)
  print(average)
study_2()

