class 매대계산기(DB생성관리):
    def __init__(self):
        super().__init__()
        self.장바구니_계산액 = 0
        self.장바구니_물건갯수 = 0
        self.장바구니_물품 = []

    def 장바구니계산(self, 장바구니):
        for 물건 in 장바구니:
            self.장바구니_계산액 += self.단가반환(물건)
            self.장바구니_물건갯수 += 1
            self.장바구니_물품.append(물건)

        return self.장바구니_계산액

    def 장바구니_물건빼기(self, 품명):
        self.장바구니_계산액 -= self.단가반환(품명)
        self.장바구니_물건갯수 -= 1
        self.장바구니_물품.remove(품명)
        return self.장바구니_계산액

    def 장바구니_결제(self, 금액):
        self.장바구니_계산액 = 0
        self.장바구니_물건갯수 = 0
        self.재고수정_물품들(self.장바구니_물품)
        self.매출기록(self.장바구니_물품)

    def 장바구니출력(self):
        print("\n=== 장바구니 ===")
        for 물건 in self.장바구니_물품:
            print(f"{물건} : {self.단가반환(물건)}원")
        print(f"총 수량: {self.장바구니_물건갯수}")
        print(f"총 금액: {self.장바구니_계산액}원")


    def 영수증출력(self):
        print("\n=== 영수증 ===")
        for 물건 in self.장바구니_물품:
            print(f"{물건} : {self.단가반환(물건)}원")
        print("------------------")
        print(f"총 결제 금액: {self.장바구니_계산액}원")

