import random

프레임당쓰러진핀 = [[0, 0] for _ in range(10)]
추가점수 = [[0, 0] for _ in range(10)]
다음투구결과를더하는횟수 = [0] * 10
프레임당점수 = [0] * 10
누적점수 = [0] * 10

for 프레임 in range(10):

    pins = random.randint(0, 10)

    # 첫 번째 투구값으로 과거 프레임 점수 업데이트
    for i in range(10):
        if 다음투구결과를더하는횟수[i] > 0:

            if 추가점수[i][0] == 0:
                추가점수[i][0] = pins
            else:
                추가점수[i][1] = pins

            다음투구결과를더하는횟수[i] -= 1

            if 다음투구결과를더하는횟수[i] == 0:
                프레임당점수[i] = (
                    프레임당쓰러진핀[i][0]
                    + 프레임당쓰러진핀[i][1]
                    + 추가점수[i][0]
                    + 추가점수[i][1]
                )

    프레임당쓰러진핀[프레임][0] = pins

    if pins == 10:
        다음투구결과를더하는횟수[프레임] = 2

    else:
        pins2 = random.randint(0, 10 - pins)
        프레임당쓰러진핀[프레임][1] = pins2

        # 두 번째 투구값으로도 과거 프레임 점수 업데이트
        for i in range(10):
            if 다음투구결과를더하는횟수[i] > 0:

                if 추가점수[i][0] == 0:
                    추가점수[i][0] = pins2
                else:
                    추가점수[i][1] = pins2

                다음투구결과를더하는횟수[i] -= 1

                if 다음투구결과를더하는횟수[i] == 0:
                    프레임당점수[i] = (
                        프레임당쓰러진핀[i][0]
                        + 프레임당쓰러진핀[i][1]
                        + 추가점수[i][0]
                        + 추가점수[i][1]
                    )

        if pins + pins2 == 10:
            다음투구결과를더하는횟수[프레임] = 1
        else:
            프레임당점수[프레임] = pins + pins2

# 누적점수 계산
누적점수[0] = 프레임당점수[0]
for i in range(1, 10):
    누적점수[i] = 누적점수[i - 1] + 프레임당점수[i]

print("프레임당 쓰러진 핀:", 프레임당쓰러진핀)
print("추가점수:", 추가점수)
print("다음투구결과를더하는횟수:", 다음투구결과를더하는횟수)
print("프레임당 점수:", 프레임당점수)
print("누적점수:", 누적점수)