import random


# ==========================================
# 기본 변수
# ==========================================

# 1~9프레임: [1구, 2구]
# 10프레임: [1구, 2구, 3구]
프레임당쓰러진핀 = [[0, 0] for _ in range(9)]
프레임당쓰러진핀.append([0, 0, 0])

# 스트라이크/스페어 보너스
추가점수 = [[0, 0] for _ in range(10)]

# 스트라이크 = 2
# 스페어 = 1
# 일반 = 0
더하는횟수 = [0] * 10

# 각 프레임 점수
프레임당점수 = [0] * 10

# 누적 점수
누적점수 = [0] * 10

# 점수 계산 완료 여부
프레임당점수계산완료여부 = [False] * 10

# 프레임별 투구 정보
프레임_정보 = [[0, 0, 0] for _ in range(10)]

프레임_인덱스 = 0
프레임_투구수 = 0


# ==========================================
# 프레임 정보 작성
# ==========================================

def 프레임_정보_작성(프레임_인덱스, 프레임_투구수, pins):

    global 더하는횟수

    # 스트라이크
    if 프레임_투구수 == 0 and pins == 10:

        더하는횟수[프레임_인덱스] = 2

    # 스페어
    elif 프레임_투구수 == 1:

        첫번째투구 = 프레임_정보[프레임_인덱스][0]

        if 첫번째투구 + pins == 10:

            더하는횟수[프레임_인덱스] = 1


# ==========================================
# 프레임 인덱스 관리
# ==========================================

def 프레임_인덱스_관리(pins):

    global 프레임_인덱스
    global 프레임_투구수

    # 현재 프레임 정보 저장
    프레임_정보[프레임_인덱스][프레임_투구수] = pins

    # 현재 프레임 정보 작성
    프레임_정보_작성(
        프레임_인덱스,
        프레임_투구수,
        pins
    )

    print(
        f"{프레임_인덱스 + 1}프레임 "
        f"{프레임_투구수 + 1}구 : {pins}"
    )

    # --------------------------------------
    # 스트라이크
    # --------------------------------------

    if 프레임_투구수 == 0 and pins == 10:

        프레임_인덱스 += 1
        프레임_투구수 = 0

    # --------------------------------------
    # 두 번째 투구까지 완료
    # --------------------------------------

    elif 프레임_투구수 == 1:

        프레임_인덱스 += 1
        프레임_투구수 = 0

    # --------------------------------------
    # 첫 번째 투구
    # --------------------------------------

    else:

        프레임_투구수 += 1


# ==========================================
# 1~9프레임 생성
# ==========================================

for 프레임 in range(9):

    # --------------------------------------
    # 첫 번째 투구
    # --------------------------------------

    pins1 = random.randint(0, 10)

    프레임_인덱스_관리(pins1)

    # --------------------------------------
    # 두 번째 투구
    # --------------------------------------

    pins2 = 0

    # 스트라이크가 아니면 두 번째 투구
    if pins1 != 10:

        pins2 = random.randint(0, 10 - pins1)

        프레임_인덱스_관리(pins2)

    # --------------------------------------
    # 프레임 결과 저장
    # --------------------------------------

    프레임당쓰러진핀[프레임][0] = pins1
    프레임당쓰러진핀[프레임][1] = pins2


# ==========================================
# 10프레임
# ==========================================

pins1 = random.randint(0, 10)


# ------------------------------------------
# 10프레임 첫 번째 투구가 스트라이크
# ------------------------------------------

if pins1 == 10:

    pins2 = random.randint(0, 10)

    # 첫 번째 투구가 스트라이크이므로
    # 두 번째 투구도 새롭게 10핀에서 시작
    pins3 = random.randint(0, 10)


# ------------------------------------------
# 첫 번째 투구가 스트라이크가 아님
# ------------------------------------------

else:

    pins2 = random.randint(0, 10 - pins1)

    # 스페어
    if pins1 + pins2 == 10:

        # 스페어이면 추가 1구
        pins3 = random.randint(0, 10)

    # 오픈
    else:

        # 추가 투구 없음
        pins3 = 0


# 10프레임 저장
프레임당쓰러진핀[9][0] = pins1
프레임당쓰러진핀[9][1] = pins2
프레임당쓰러진핀[9][2] = pins3


# ==========================================
# 추가점수 계산
# ==========================================

for i in range(9):

    # 스트라이크
    if 더하는횟수[i] == 2:

        추가점수[i][0] = 프레임당쓰러진핀[i + 1][0]
        추가점수[i][1] = 프레임당쓰러진핀[i + 1][1]

    # 스페어
    elif 더하는횟수[i] == 1:

        추가점수[i][0] = 프레임당쓰러진핀[i + 1][0]


# ==========================================
# 프레임별 점수 계산
# ==========================================

for i in range(10):

    # --------------------------------------
    # 1~9프레임
    # --------------------------------------

    if i < 9:

        첫번째 = 프레임당쓰러진핀[i][0]
        두번째 = 프레임당쓰러진핀[i][1]

        # 스트라이크
        if 더하는횟수[i] == 2:

            프레임당점수[i] = (
                10
                + 추가점수[i][0]
                + 추가점수[i][1]
            )

        # 스페어
        elif 더하는횟수[i] == 1:

            프레임당점수[i] = (
                10
                + 추가점수[i][0]
            )

        # 오픈
        else:

            프레임당점수[i] = (
                첫번째
                + 두번째
            )


    # --------------------------------------
    # 10프레임
    # --------------------------------------

    else:

        첫번째 = 프레임당쓰러진핀[i][0]
        두번째 = 프레임당쓰러진핀[i][1]
        세번째 = 프레임당쓰러진핀[i][2]

        프레임당점수[i] = (
            첫번째
            + 두번째
            + 세번째
        )

    프레임당점수계산완료여부[i] = True


# ==========================================
# 누적점수 계산
# ==========================================

for i in range(10):

    if i == 0:

        누적점수[i] = 프레임당점수[i]

    else:

        누적점수[i] = (
            누적점수[i - 1]
            + 프레임당점수[i]
        )


# ==========================================
# 결과 출력
# ==========================================

print()
print("=" * 60)
