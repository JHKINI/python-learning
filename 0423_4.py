import random

프레임당쓰러진핀 = [[0, 0] for _ in range(10)]
추가점수 = [[0, 0] for _ in range(10)]
다음투구결과를더하는횟수 = [0] * 10
프레임당점수 = [0] * 10
누적점수 = [0] * 10


def 과거프레임업데이트(투구값):
    for i in range(10):
        if 다음투구결과를더하는횟수[i] > 0:

            if 추가점수[i][0] == 0:
                추가점수[i][0] = 투구값
            else:
                추가점수[i][1] = 투구값

            다음투구결과를더하는횟수[i] -= 1

            if 다음투구결과를더하는횟수[i] == 0:
                프레임당점수[i] = (
                    프레임당쓰러진핀[i][0]
                    + 프레임당쓰러진핀[i][1]
                    + 추가점수[i][0]
                    + 추가점수[i][1]
                )


# 1~9프레임(인덱스 0~8) 처리
for 프레임 in range(9):

    pins = random.randint(0, 10)

    # 첫 번째 투구값으로 과거 프레임 점수 업데이트
    과거프레임업데이트(pins)

    프레임당쓰러진핀[프레임][0] = pins

    if pins == 10:
        # 스트라이크
        다음투구결과를더하는횟수[프레임] = 2

    else:
        pins2 = random.randint(0, 10 - pins)

        # 두 번째 투구값으로 과거 프레임 점수 업데이트
        과거프레임업데이트(pins2)

        프레임당쓰러진핀[프레임][1] = pins2

        if pins + pins2 == 10:
            # 스페어
            다음투구결과를더하는횟수[프레임] = 1
        else:
            # 오픈 프레임
            프레임당점수[프레임] = pins + pins2


# 10프레임(인덱스 9) 따로 처리
프레임 = 9

pins = random.randint(0, 10)
과거프레임업데이트(pins)
프레임당쓰러진핀[프레임][0] = pins

if pins == 10:
    # 10프레임 첫 투구 스트라이크 -> 보너스 2번
    pins2 = random.randint(0, 10)
    과거프레임업데이트(pins2)

    프레임당쓰러진핀[프레임][1] = pins2

    if pins2 == 10:
        보너스투구 = random.randint(0, 10)
    else:
        보너스투구 = random.randint(0, 10 - pins2)

    과거프레임업데이트(보너스투구)

    프레임당점수[프레임] = pins + pins2 + 보너스투구

else:
    pins2 = random.randint(0, 10 - pins)
    과거프레임업데이트(pins2)

    프레임당쓰러진핀[프레임][1] = pins2

    if pins + pins2 == 10:
        # 10프레임 스페어 -> 보너스 1번
        보너스투구 = random.randint(0, 10)
        과거프레임업데이트(보너스투구)

        프레임당점수[프레임] = pins + pins2 + 보너스투구
    else:
        # 10프레임 오픈
        프레임당점수[프레임] = pins + pins2


# 누적점수 계산
누적점수[0] = 프레임당점수[0]
for i in range(1, 10):
    누적점수[i] = 누적점수[i - 1] + 프레임당점수[i]

print("프레임당 쓰러진 핀:", 프레임당쓰러진핀)
print("추가점수:", 추가점수)
print("다음투구결과를더하는횟수:", 다음투구결과를더하는횟수)
print("프레임당 점수:", 프레임당점수)
print("누적점수:", 누적점수)