
import random as rand
물품명=["사과","비누","멸치","기름"]
장바구니물품갯수 = rand.randint(1,30)

장바구니={} #{물품이름:{물품이름,갯수},...}
for i in range(장바구니물품갯수):
        물품이름 = rand.choice(물품명)

        if 장바구니. get(물품이름)==None:
                장바구니 [물품이름] = {"품명":물품이름,"갯수":1}
        else:
                장바구니[물품이름]["갯수"]=장바구니[물품이름]["갯수"]+1

print(장바구니)


